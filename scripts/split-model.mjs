/**
 * Split the GGUF model into bundle-safe chunks.
 *
 * WHY: Android caps a single packaged asset around 200MB. Our ~350MB .gguf
 * can't ship as one asset, so we split it into ~40MB .bin chunks that Metro
 * bundles individually, then reassemble them on first launch (see
 * src/ai/model.ts).
 *
 * USAGE:
 *   1) Put the model file at:  models/qwen2.5-0.5b-instruct-q4_k_m.gguf
 *      (download it once, e.g. from the Qwen GGUF repo on Hugging Face).
 *   2) Run:  npm run split-model
 *
 * OUTPUT (into assets/model/):
 *   chunk-000.bin, chunk-001.bin, ...   the raw pieces
 *   manifest.json                       filename, totalBytes, ordered chunks
 *   chunks.ts                           require() map so Metro bundles them
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const MODEL_FILENAME = 'qwen2.5-0.5b-instruct-q4_k_m.gguf';
const SRC = path.join(root, 'models', MODEL_FILENAME);
const OUT_DIR = path.join(root, 'assets', 'model');
const CHUNK_SIZE = 40 * 1024 * 1024; // 40MB — safely under Android's asset cap

function main() {
  if (!fs.existsSync(SRC)) {
    console.error(`\n✗ Model not found: ${SRC}`);
    console.error(`  Download the GGUF and place it there, then re-run.\n`);
    process.exit(1);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Clean any previous chunks.
  for (const f of fs.readdirSync(OUT_DIR)) {
    if (f.startsWith('chunk-') || f === 'manifest.json' || f === 'chunks.ts') {
      fs.rmSync(path.join(OUT_DIR, f));
    }
  }

  const totalBytes = fs.statSync(SRC).size;
  const fd = fs.openSync(SRC, 'r');
  const buf = Buffer.alloc(CHUNK_SIZE);
  const chunks = [];
  let index = 0;
  let bytesRead;

  console.log(`Splitting ${MODEL_FILENAME} (${(totalBytes / 1e6).toFixed(1)} MB)…`);
  while ((bytesRead = fs.readSync(fd, buf, 0, CHUNK_SIZE, null)) > 0) {
    const name = `chunk-${String(index).padStart(3, '0')}.bin`;
    fs.writeFileSync(path.join(OUT_DIR, name), buf.subarray(0, bytesRead));
    chunks.push(name);
    process.stdout.write(`  ${name} (${(bytesRead / 1e6).toFixed(1)} MB)\n`);
    index++;
  }
  fs.closeSync(fd);

  // manifest.json
  fs.writeFileSync(
    path.join(OUT_DIR, 'manifest.json'),
    JSON.stringify({ filename: MODEL_FILENAME, totalBytes, chunks }, null, 2),
  );

  // chunks.ts — a require() map so Metro includes each chunk in the bundle.
  const lines = [
    '// AUTO-GENERATED by scripts/split-model.mjs. Do not edit.',
    'export const chunkModules: Record<string, number> = {',
    ...chunks.map((c) => `  '${c}': require('./${c}'),`),
    '};',
    '',
  ];
  fs.writeFileSync(path.join(OUT_DIR, 'chunks.ts'), lines.join('\n'));

  console.log(`\n✓ Wrote ${chunks.length} chunks + manifest.json + chunks.ts to assets/model/`);
  console.log(`  Metro will bundle these; the app reassembles on first launch.\n`);
}

main();
